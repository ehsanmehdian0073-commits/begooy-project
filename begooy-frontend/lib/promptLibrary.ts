// ───────────────────────────────────────────────────────────────────────────────
// متغیرهای ضروری هر قالب + توابع موردنیاز ویزارد

const TEMPLATE_REQUIRED_VARS: Record<TemplateKey, string[]> = {
  support: ["brand", "working_hours", "support_link"],
  sales: ["brand", "checkout_link"],
  education: ["brand"],
  booking: ["brand", "booking_link"],
  hr: ["brand", "hr_form"],
};

/** فهرست متغیرهای ضروری برای یک TemplateKey (برای UI) */
export function getRequiredVarsForTemplate(tpl: TemplateKey): string[] {
  return TEMPLATE_REQUIRED_VARS[tpl] ?? [];
}

/** بررسی کمبود متغیرها نسبت به قالب انتخاب‌شده (برای هشدار Step 6) */
export function validateVars(
  tpl: TemplateKey,
  vars: Record<string, string> = {}
): string[] {
  const required = getRequiredVarsForTemplate(tpl);
  return required.filter((k) => !vars[k] || vars[k].trim() === "");
}

// ───────────────────────────────────────────────────────────────────────────────
// ابزارهای ساخت/پرکردن پرامپت

/**
 * متغیرهای {{var}} را با مقادیر vars جایگزین می‌کند.
 * اگر متغیری وجود نداشت، همان {{var}} باقی می‌ماند تا توسعه‌دهنده متوجه کمبود شود.
 */
export function fillPrompt(template: string, vars: Record<string, string>): string {
  return template.replace(/\{\{(\w+)\}\}/g, (_, k) => (vars?.[k] ?? `{{${k}}}`));
}

/**
 * پرامپت نهایی را بر اساس صنعت و قالب می‌سازد و سپس با vars پر می‌کند.
 * اگر پرامپت مخصوص صنعت/قالب پیدا نشود، از general.support به عنوان بکاپ استفاده می‌شود.
 */
export function buildPrompt(
  industry: Industry,
  tpl: TemplateKey,
  vars: Record<string, string>
): string {
  const base =
    PROMPT_MATRIX[industry]?.[tpl] ??
    PROMPT_MATRIX.general.support ??
    "";
  return fillPrompt(base, vars);
}

/** دسترسی ساده به پرامپت خام (بدون پرکردن متغیرها) */
export function getRawTemplate(industry: Industry, tpl: TemplateKey): string | undefined {
  return PROMPT_MATRIX[industry]?.[tpl] ?? PROMPT_MATRIX.general.support;
}
